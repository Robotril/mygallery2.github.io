// Reads frames/<clip>/sfx.json from the capture and writes src/gameSfx.ts: clip frame counts + game sound events.
import fs from 'fs';
const clips = fs.readdirSync('frames').filter((c) => fs.statSync('frames/' + c).isDirectory());
const CLIP_FRAMES = {}, GAME = {};
for (const c of clips) {
  CLIP_FRAMES[c] = fs.readdirSync('frames/' + c).filter((x) => x.endsWith('.jpg')).length;
  try { GAME[c] = JSON.parse(fs.readFileSync(`frames/${c}/sfx.json`, 'utf8')); } catch { GAME[c] = []; }
}
fs.writeFileSync('src/gameSfx.ts', `// generated by scripts-gen-sfx.mjs from the capture logs\nexport const CLIP_FRAMES: Record<string, number> = ${JSON.stringify(CLIP_FRAMES)};\nexport type GameEv = { n: string; f: number; a: unknown };\nexport const GAME_SFX: Record<string, GameEv[]> = ${JSON.stringify(GAME)};\n`);
console.log(CLIP_FRAMES, Object.fromEntries(Object.entries(GAME).map(([k, v]) => [k, v.reduce((o, e) => (o[e.n] = (o[e.n] || 0) + 1, o), {})])));
